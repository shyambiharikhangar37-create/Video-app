import com.example.player.AndroidYouTubeWebView
import com.example.ui.theme.CrimsonAccent
import com.example.ui.theme.TextPrimary

@Composable
fun FullscreenPlayerDialog(
    video: VideoItem,
    onClose: () -> Unit
) {
    BackHandler {
        onClose()
    }

    Dialog(
        onDismissRequest = onClose,
        properties = DialogProperties(
            usePlatformDefaultWidth = false,
            decorFitsSystemWindows = false
        )
    ) {
        Box(
            modifier = Modifier
                .fillMaxSize()
                .background(Color.Black)
        ) {
            // Live video view filling the entire screen
            AndroidYouTubeWebView(
                youtubeId = video.youtubeId,
                autoplay = true,
                modifier = Modifier.fillMaxSize()
            )

            // Top overlay bar with title and close button
            Surface(
                color = Color.Black.copy(alpha = 0.6f),
                modifier = Modifier
                    .fillMaxWidth()
                    .align(Alignment.TopCenter)
                    .statusBarsPadding()
            ) {
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(horizontal = 12.dp, vertical = 8.dp),
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Text(
                        text = video.title,
                        color = TextPrimary,
                        fontSize = 15.sp,
                        fontWeight = FontWeight.SemiBold,
                        maxLines = 1,
                        overflow = TextOverflow.Ellipsis,
                        modifier = Modifier.weight(1f)
                    )

                    Surface(
                        shape = CircleShape,
                        color = CrimsonAccent.copy(alpha = 0.85f),
                        modifier = Modifier.size(36.dp)
                    ) {
                        IconButton(onClick = onClose) {
                            Icon(
                                Icons.Default.Close,
                                contentDescription = "Close Fullscreen",
                                tint = Color.White,
                                modifier = Modifier.size(20.dp)
                            )
                        }
                    }
                }
            }
        }
    }
}
